// @effect-diagnostics nodeBuiltinImport:off - finds and generates fixture files from Node, outside any Effect runtime.
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

import { afterAll, beforeAll, type TestContext } from "vite-plus/test";

import {
  fixturePath,
  fixtureProblem,
  harFixture,
  type HarFixture,
} from "../../../scripts/fixtures/fixtures.ts";
import { ensureFixture } from "../../../scripts/fixtures/generate.ts";

export interface CachedHar {
  readonly path: string;
  /** The generator's manifest entry: the sizes the file was written to. */
  readonly spec: HarFixture;
  /** Why the tests on it skip, ending in the command that generates it; null when it is there. */
  readonly missing: string | null;
}

/**
 * A multi-gigabyte HAR from the fixture cache (`vp run fixtures`). It is never
 * generated by a test: when it is absent, the tests on it skip and say how to
 * generate it.
 */
export function cachedHar(name: string): CachedHar {
  const missing = fixtureProblem(name);
  if (missing !== null) console.warn(`skipping the tests on ${name}: ${missing}`);
  return { path: fixturePath(name), spec: harFixture(name), missing };
}

/** Skips the running test, with the reason as its note, when the fixture is absent. */
export function skipWithout(context: TestContext, fixture: CachedHar): void {
  if (fixture.missing !== null) context.skip(fixture.missing);
}

/**
 * A small fixture (1 MB class): the cached copy, or one generated for this test
 * file with the default seed when the cache has none, so a fresh clone runs it.
 */
export function useSmallFixture(name: string): () => string {
  let scratch = "";
  let path = "";
  beforeAll(() => {
    scratch = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "quipu-e2e-fixture-"));
    path = ensureFixture(name, scratch).path;
  });
  afterAll(() => {
    NodeFS.rmSync(scratch, { recursive: true, force: true });
  });
  return () => {
    if (path === "") throw new Error(`${name} is read before its beforeAll ran`);
    return path;
  };
}

/**
 * Real HAR captures some decoder tests read. They are not in the repository:
 * `QUIPU_HAR_SAMPLES` names a directory of them, and without it those tests skip.
 */
export const REFERENCE_HAR_SAMPLES = process.env.QUIPU_HAR_SAMPLES?.trim() ?? "";

/** Why the real-capture tests skip, or null when the reference captures are there. */
export const referenceSamplesMissing: string | null =
  REFERENCE_HAR_SAMPLES === ""
    ? "QUIPU_HAR_SAMPLES is not set; point it at a directory of real HAR captures to run these tests"
    : NodeFS.existsSync(REFERENCE_HAR_SAMPLES)
      ? null
      : `QUIPU_HAR_SAMPLES points at ${REFERENCE_HAR_SAMPLES}, which does not exist`;
if (referenceSamplesMissing !== null)
  console.warn(`skipping the real-capture tests: ${referenceSamplesMissing}`);
